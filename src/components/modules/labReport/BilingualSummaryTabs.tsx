"use client";

import React, { useState } from "react";
import { Languages, AlertCircle, FileText } from "lucide-react";

interface BilingualSummaryTabsProps {
  summaryEn?: string;
  summaryBn?: string;
  disclaimer?: string;
}

export function BilingualSummaryTabs({
  summaryEn,
  summaryBn,
  disclaimer,
}: BilingualSummaryTabsProps) {
  const [activeTab, setActiveTab] = useState<"bn" | "en">("bn");

  return (
    <div className="space-y-3">
      {/* Header & Language Switcher */}
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-2 text-zinc-900 dark:text-zinc-100 font-bold text-xs uppercase tracking-wide">
          <FileText className="h-4 w-4 text-blue-600 dark:text-blue-400" />
          <span>Multimodal AI Executive Summary</span>
        </div>

        {/* Tab Controls */}
        <div className="flex items-center gap-1 bg-zinc-100 dark:bg-zinc-800 p-1 rounded-xl text-xs font-semibold">
          <button
            type="button"
            onClick={() => setActiveTab("bn")}
            className={`flex items-center gap-1.5 px-3 py-1 rounded-lg transition-all ${
              activeTab === "bn"
                ? "bg-blue-600 text-white shadow-xs font-bold"
                : "text-zinc-600 dark:text-zinc-400 hover:text-zinc-900 dark:hover:text-zinc-100"
            }`}
          >
            <Languages className="h-3.5 w-3.5" />
            <span>বাংলা ব্যাখ্যা</span>
          </button>
          <button
            type="button"
            onClick={() => setActiveTab("en")}
            className={`flex items-center gap-1.5 px-3 py-1 rounded-lg transition-all ${
              activeTab === "en"
                ? "bg-blue-600 text-white shadow-xs font-bold"
                : "text-zinc-600 dark:text-zinc-400 hover:text-zinc-900 dark:hover:text-zinc-100"
            }`}
          >
            <span>English (Clinical)</span>
          </button>
        </div>
      </div>

      {/* Content Container */}
      <div className="rounded-2xl border border-zinc-200 dark:border-zinc-800 bg-white dark:bg-zinc-900 p-4 sm:p-5 shadow-xs">
        {activeTab === "bn" ? (
          <div className="text-sm text-zinc-800 dark:text-zinc-200 leading-relaxed font-sans whitespace-pre-line">
            {summaryBn ||
              summaryEn ||
              "এই ল্যাব রিপোর্টের জন্য বিস্তারিত বাংলা ব্যাখ্যা প্রস্তুত করা হচ্ছে..."}
          </div>
        ) : (
          <div className="text-sm text-zinc-800 dark:text-zinc-200 leading-relaxed whitespace-pre-line">
            {summaryEn ||
              summaryBn ||
              "Clinical summary is being prepared by our multimodal AI clinical engine..."}
          </div>
        )}

        {/* Clinical Safety Disclaimer */}
        <div className="mt-4 pt-3 border-t border-zinc-100 dark:border-zinc-800 flex items-start gap-2 text-[11px] text-zinc-500 dark:text-zinc-400">
          <AlertCircle className="h-4 w-4 text-amber-500 shrink-0 mt-0.5" />
          <p>
            {disclaimer ||
              "Disclaimer: This AI summary is generated by our clinical vision engine for informational and preparation purposes only. It is not a definitive clinical diagnosis. Please discuss these findings with your certified medical doctor."}
          </p>
        </div>
      </div>
    </div>
  );
}
